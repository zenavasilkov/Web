function generateNickname() {
    const firstName = firstNameInput.value.trim();
    const lastName = lastNameInput.value.trim();

    if (!firstName || !lastName) {
        alert('Сначала введите имя и фамилию');
        return;
    }

    nicknameAttempts++;
    nicknameAttemptsEl.textContent = `Попыток генерации: ${nicknameAttempts}/5`;

    if (nicknameAttempts > 5) {
        nicknameInput.readOnly = false;
        nicknameInput.focus();
        generateNicknameBtn.textContent = '✏️ Редактировать';
        return;
    }

    const firstLetters = firstName.slice(0, Math.floor(Math.random() * 3) + 1).toLowerCase();
    const lastLetters = lastName.slice(0, Math.floor(Math.random() * 3) + 1).toLowerCase();

    const number = Math.floor(Math.random() * 9900) + 100;

    const suffixes = ['_', 'x', 'z', 'pro', 'official', 'real', 'the', 'mr', 'ms', 'dev', 'art', 'design'];
    const suffix = Math.random() > 0.3 ? suffixes[Math.floor(Math.random() * suffixes.length)] : '';

    const nickname = `${firstLetters}${lastLetters}${number}${suffix}`;
    nicknameInput.value = nickname;

    checkNicknameUniqueness(nickname);
}

async function checkNicknameUniqueness(nickname) {
    try {
        const response = await fetch(`${API_BASE_URL}/users`);
        const allUsers = await response.json();

        const errorEl = document.getElementById('nicknameError');
        const successEl = document.getElementById('nicknameSuccess');

        const exists = allUsers.some(user => user.nickname === nickname);

        if (exists) {
            errorEl.textContent = 'Этот никнейм уже занят. Попробуйте сгенерировать другой.';
            successEl.textContent = '';
            nicknameInput.classList.add('error');
            nicknameInput.classList.remove('success');
            return false;
        }

        errorEl.textContent = '';
        successEl.textContent = '✓ Никнейм доступен';
        nicknameInput.classList.remove('error');
        nicknameInput.classList.add('success');
        return true;
    } catch (error) {
        console.error('Ошибка проверки никнейма:', error);
        return true;
    }
}

