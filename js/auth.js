async function hashPassword(password) {
    const encoder = new TextEncoder();
    const data = encoder.encode(password);

    const hashBuffer = await crypto.subtle.digest('SHA-256', data);

    const hashArray = Array.from(new Uint8Array(hashBuffer));
    return hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
}

function formatPhoneBy(value) {
    let digits = value.replace(/\D/g, '');

    if (digits.startsWith('375')) {
        digits = digits.slice(0, 12);
    } else if (digits.startsWith('8')) {
        digits = '375' + digits.slice(1, 11);
    } else if (digits.length > 0 && !digits.startsWith('375')) {
        if (digits.length <= 2) {
            digits = '375' + digits;
        } else {
            digits = '375' + digits.slice(0, 9);
        }
    }

    let formattedValue = '';

    if (digits.length > 0) {
        formattedValue = '+' + digits.slice(0, 3);
    }
    if (digits.length > 3) {
        formattedValue += ' (' + digits.slice(3, 5);
        if (digits.length > 5) {
            formattedValue += ') ';
        }
    }
    if (digits.length > 5) {
        formattedValue += digits.slice(5, 8);
    }
    if (digits.length > 8) {
        formattedValue += '-' + digits.slice(8, 10);
    }
    if (digits.length > 10) {
        formattedValue += '-' + digits.slice(10, 12);
    }

    return formattedValue;
}

