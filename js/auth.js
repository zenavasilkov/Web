function validateDateOfBirth() {
    const dateOfBirth = dateOfBirthInput.value;
    const errorEl = document.getElementById('dateOfBirthError');
    const successEl = document.getElementById('dateOfBirthSuccess');

    if (!dateOfBirth) {
        errorEl.textContent = '';
        successEl.textContent = '';
        dateOfBirthInput.classList.remove('error', 'success');
        return false;
    }

    const birthDate = new Date(dateOfBirth);
    const today = new Date();
    const age = today.getFullYear() - birthDate.getFullYear();
    const monthDiff = today.getMonth() - birthDate.getMonth();

    let actualAge = age;
    if (monthDiff < 0 || (monthDiff === 0 && today.getDate() < birthDate.getDate())) {
        actualAge--;
    }

    if (actualAge < 16) {
        errorEl.textContent = `Вам должно исполниться 16 лет. Сейчас вам ${actualAge} лет.`;
        successEl.textContent = '';
        dateOfBirthInput.classList.add('error');
        dateOfBirthInput.classList.remove('success');
        return false;
    }

    errorEl.textContent = '';
    successEl.textContent = '✓ Возраст соответствует требованиям';
    dateOfBirthInput.classList.remove('error');
    dateOfBirthInput.classList.add('success');
    return true;
}

