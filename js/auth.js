function validatePassword() {
    if (!isPasswordMethodManual) return true;

    const password = passwordInput.value;
    const errorEl = document.getElementById('passwordError');
    const successEl = document.getElementById('passwordSuccess');

    updatePasswordRequirements(password);

    if (password.length === 0) {
        errorEl.textContent = '';
        successEl.textContent = '';
        passwordInput.classList.remove('error', 'success');
        return false;
    }

    if (password.length < 8 || password.length > 20) {
        errorEl.textContent = 'Пароль должен содержать от 8 до 20 символов';
        successEl.textContent = '';
        passwordInput.classList.add('error');
        passwordInput.classList.remove('success');
        return false;
    }

    if (!/[A-Z]/.test(password)) {
        errorEl.textContent = 'Пароль должен содержать хотя бы одну заглавную букву';
        successEl.textContent = '';
        passwordInput.classList.add('error');
        passwordInput.classList.remove('success');
        return false;
    }

    if (!/[a-z]/.test(password)) {
        errorEl.textContent = 'Пароль должен содержать хотя бы одну строчную букву';
        successEl.textContent = '';
        passwordInput.classList.add('error');
        passwordInput.classList.remove('success');
        return false;
    }

    if (!/[0-9]/.test(password)) {
        errorEl.textContent = 'Пароль должен содержать хотя бы одну цифру';
        successEl.textContent = '';
        passwordInput.classList.add('error');
        passwordInput.classList.remove('success');
        return false;
    }

    if (!/[!@#$%^&*()_+\-=\[\]{}|;:,.<>?]/.test(password)) {
        errorEl.textContent = 'Пароль должен содержать хотя бы один специальный символ';
        successEl.textContent = '';
        passwordInput.classList.add('error');
        passwordInput.classList.remove('success');
        return false;
    }

    if (TOP_100_PASSWORDS.includes(password.toLowerCase())) {
        errorEl.textContent = 'Этот пароль слишком распространён. Выберите другой.';
        successEl.textContent = '';
        passwordInput.classList.add('error');
        passwordInput.classList.remove('success');
        return false;
    }

    errorEl.textContent = '';
    successEl.textContent = '✓ Пароль соответствует требованиям';
    passwordInput.classList.remove('error');
    passwordInput.classList.add('success');
    return true;
}

function updatePasswordRequirements(password) {
    document.getElementById('req-length').className = 'req-item ' + (password.length >= 8 && password.length <= 20 ? 'valid' : 'invalid');
    document.getElementById('req-uppercase').className = 'req-item ' + (/[A-Z]/.test(password) ? 'valid' : 'invalid');
    document.getElementById('req-lowercase').className = 'req-item ' + (/[a-z]/.test(password) ? 'valid' : 'invalid');
    document.getElementById('req-number').className = 'req-item ' + (/[0-9]/.test(password) ? 'valid' : 'invalid');
    document.getElementById('req-special').className = 'req-item ' + (/[!@#$%^&*()_+\-=\[\]{}|;:,.<>?]/.test(password) ? 'valid' : 'invalid');
    document.getElementById('req-common').className = 'req-item ' + (!TOP_100_PASSWORDS.includes(password.toLowerCase()) ? 'valid' : 'invalid');
}

