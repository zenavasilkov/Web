function validateForm() {
    const isPhoneValid = validatePhone();
    const isEmailValid = validateEmail();
    const isDateValid = validateDateOfBirth();
    const isPasswordValid = isPasswordMethodManual ? validatePassword() && validatePasswordRepeat() : true;
    const isFirstNameValid = validateName(firstNameInput, 'firstNameError');
    const isLastNameValid = validateName(lastNameInput, 'lastNameError');
    const isNicknameValid = nicknameInput.value.length > 0;
    const isAgreementValid = validateAgreement();

    const isValid = isPhoneValid && isEmailValid && isDateValid && isPasswordValid &&
        isFirstNameValid && isLastNameValid && isNicknameValid && isAgreementValid;

    submitBtn.disabled = !isValid;
    return isValid;
}

form.addEventListener('submit', async (e) => {
    e.preventDefault();

    if (!validateForm()) {
        alert('Пожалуйста, исправьте ошибки в форме');
        return;
    }

    const rawPassword = isPasswordMethodManual ? passwordInput.value : autoGeneratedPassword;

    const hashedPassword = await hashPassword(rawPassword);

    const userData = {
        phone: phoneInput.value.replace(/\D/g, ''),
        email: emailInput.value.trim(),
        password: hashedPassword,
        dateOfBirth: dateOfBirthInput.value,
        firstName: firstNameInput.value.trim(),
        lastName: lastNameInput.value.trim(),
        patronymic: patronymicInput.value.trim(),
        nickname: nicknameInput.value.trim(),
        role: 'user',
        agreementAccepted: agreementCheckbox.checked,
        createdAt: new Date().toISOString()
    };

    try {
        const nicknameCheck = await checkNicknameUniqueness(userData.nickname);
        if (!nicknameCheck) {
            alert('Этот никнейм уже занят. Пожалуйста, выберите другой.');
            return;
        }

        const response = await fetch(`${API_BASE_URL}/users`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(userData)
        });

        if (response.ok) {
            const newUser = await response.json();
            const { password, ...safeUser } = newUser;
            localStorage.setItem('currentUser', JSON.stringify(safeUser));

            alert('✅ Регистрация успешна! Добро пожаловать!');
            window.location.href = 'catalog.html';
        } else {
            alert('❌ Ошибка при регистрации. Попробуйте ещё раз.');
        }
    } catch (error) {
        console.error('Ошибка регистрации:', error);
        alert('❌ Произошла ошибка при регистрации');
    }
});

