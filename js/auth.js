function validatePhone() {
    const phone = phoneInput.value.replace(/\D/g, '');
    const errorEl = document.getElementById('phoneError');
    const successEl = document.getElementById('phoneSuccess');

    if (phone.length === 0) {
        errorEl.textContent = '';
        successEl.textContent = '';
        phoneInput.classList.remove('error', 'success');
        return false;
    }

    if (phone.length !== 12) {
        errorEl.textContent = `Номер телефона должен содержать 12 цифр (сейчас: ${phone.length}). Пример: +375291234567`;
        successEl.textContent = '';
        phoneInput.classList.add('error');
        phoneInput.classList.remove('success');
        return false;
    }

    if (!phone.startsWith('375')) {
        errorEl.textContent = 'Разрешена регистрация только на номера Республики Беларусь (+375)';
        successEl.textContent = '';
        phoneInput.classList.add('error');
        phoneInput.classList.remove('success');
        return false;
    }

    const operatorCode = phone.slice(3, 5);
    const validCodes = ['25', '29', '33', '44'];

    if (!validCodes.includes(operatorCode)) {
        errorEl.textContent = `Неверный код оператора (${operatorCode}). Допустимые коды: 25, 29, 33, 44`;
        successEl.textContent = '';
        phoneInput.classList.add('error');
        phoneInput.classList.remove('success');
        return false;
    }

    errorEl.textContent = '';
    successEl.textContent = '✓ Номер телефона корректен';
    phoneInput.classList.remove('error');
    phoneInput.classList.add('success');
    return true;
}

